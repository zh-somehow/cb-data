    CB_LIST_URL = "https://www.jisilu.cn/data/cbnew/cb_list_new/"

    HEADERS = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/120.0.0.0 Safari/537.36"
        ),
        "Referer": "https://www.jisilu.cn/login/",
        "Accept": "application/json, text/javascript, */*; q=0.01",
        "Content-Type": "application/x-www-form-urlencoded; charset=UTF-8",
        "X-Requested-With": "XMLHttpRequest",
    }

    def __init__(self, username: str, password: str):
        self.username = username
        self.password = password
        self.session = requests.Session()
        self.session.headers.update(self.HEADERS)

    # ── AES 加密 ─────────────────────────────────────────────────────────────
    @staticmethod
    def _aes_encrypt(text: str) -> str:
        """
        集思录登录加密：AES-ECB，PKCS7填充，密钥固定为 397151C04723421F，输出 hex
        """
        key = b"397151C04723421F"
        cipher = AES.new(key, AES.MODE_ECB)
        encrypted = cipher.encrypt(pad(text.encode("utf-8"), AES.block_size))
        return encrypted.hex()

    # ── AES 加密（ECB + Pkcs7，输出 hex）────────────────────────────────────
    def _aes_encrypt(self, text: str) -> str:
        cipher = AES.new(self.AES_KEY, AES.MODE_ECB)
        encrypted = cipher.encrypt(pad(text.encode("utf-8"), AES.block_size))
        return encrypted.hex()

    # ── 登录 ────────────────────────────────────────────────────────────────
